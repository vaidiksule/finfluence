create table if not exists public.research_runs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete set null,
  input_text text not null,
  input_kind text not null check (input_kind in ('question', 'url', 'headline', 'article_text')),
  status text not null default 'received' check (status in ('received', 'searching', 'extracting', 'resolving', 'auditing', 'completed', 'failed')),
  search_provider text,
  error text,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

alter table public.articles
  add column if not exists research_run_id uuid references public.research_runs(id) on delete set null;

create table if not exists public.source_documents (
  id uuid primary key default gen_random_uuid(),
  research_run_id uuid not null references public.research_runs(id) on delete cascade,
  article_id text references public.articles(id) on delete set null,
  url text not null,
  canonical_url text,
  publisher text,
  title text,
  snippet text,
  published_at timestamptz,
  retrieved_at timestamptz not null default now(),
  content_hash text,
  search_rank integer,
  source_kind text not null default 'search_result',
  created_at timestamptz not null default now()
);

create table if not exists public.graph_events (
  id bigint generated by default as identity primary key,
  research_run_id uuid references public.research_runs(id) on delete cascade,
  event_type text not null,
  payload jsonb not null default '{}',
  created_at timestamptz not null default now()
);

create index if not exists research_runs_created_idx on public.research_runs (created_at desc);
create index if not exists source_documents_run_idx on public.source_documents (research_run_id);
create index if not exists graph_events_run_idx on public.graph_events (research_run_id, created_at);

alter table public.research_runs enable row level security;
alter table public.source_documents enable row level security;
alter table public.graph_events enable row level security;

create policy "users can read their research runs" on public.research_runs
  for select using (auth.uid() = user_id or user_id is null);
create policy "users can read research sources" on public.source_documents
  for select using (exists (select 1 from public.research_runs r where r.id = research_run_id and (r.user_id = auth.uid() or r.user_id is null)));
create policy "users can read research graph events" on public.graph_events
  for select using (exists (select 1 from public.research_runs r where r.id = research_run_id and (r.user_id = auth.uid() or r.user_id is null)));

alter publication supabase_realtime add table public.research_runs;
alter publication supabase_realtime add table public.source_documents;
alter publication supabase_realtime add table public.graph_events;
